"""
Builds src/data/geometry.json from the project's own spatial data (used by site-v2).

Inputs
  - STEP_BM_SIG_DATA/Limite_STEPBM.lpkx and STEP_BM_Compo.lpkx (ArcGIS layer packages,
    CRS: Merchich / Nord Maroc, EPSG:26191)
  - tools/render-model/masks/*.png : orthographic silhouettes of GLB model parts
    (produced by tools/render-model, same framing as public/media/model/plan-top.webp)

Output (all local coordinates in metres, origin = top-left corner of the model extent,
x to the east, y to the south; the top view image covers exactly this extent)
  extent, boundary (local + WGS84), imageCorners (WGS84), center, footprints per unit.

Usage:  python tools/build_geometry.py <path to STEP Beni Mellal folder>
Requires: py7zr geopandas pyproj opencv-python
"""
import json, sys, os, tempfile, glob
import py7zr, geopandas as gpd, numpy as np, cv2
from pyproj import Transformer

ROOT = sys.argv[1] if len(sys.argv) > 1 else '..'
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'data', 'geometry.json')
HX, HZ = 289.7, 385.32            # half extent of the 3D model (manifest "site" bbox)
W_M, H_M = 2 * HX, 2 * HZ

# unit id -> footprint source. 'gis:' = polygons of the GIS composition (field Name),
# 'mask:' = silhouette of 3D model parts (tools/render-model/masks/<name>.png)
FOOTPRINTS = {
    'pretraitement':          ['mask:Pretraitement'],
    'bassins-anaerobies':     ['gis:Bassin de décantation primaire'],
    'bassins-decantation':    ['gis:Bassins de décantation'],
    'lits-sechage':           ['gis:Bassin de séchage'],
    'fosse-vannes-lb':        ['mask:Fosse_vannes_LB'],
    'lits-bacteriens':        ['gis:Lit Bactérien'],
    'clarificateurs':         ['gis:Clarificateur', 'gis:Petit Clarificateur'],
    'maturation':             ['gis:Bassin de maturation'],
    'station-pompage':        ['mask:Station_pompage'],
    'filtration-coagulation': ['mask:Filtration_coagulation'],
    'zone-uv':                ['mask:Zone_UV_dalle_basse'],
    'eau-sale-lavage':        ['gis:Eau sale de lavage'],
    'centre-controle':        ['gis:Centre de contrôle'],
    'chambre-pompes':         ['gis:Chambres des pompes'],
    'cuves':                  ['mask:Cuves_blanches'],
    'batiments':              ['mask:Batiments'],
}

def extract(lpkx, tmp):
    with py7zr.SevenZipFile(lpkx) as z:
        z.extractall(tmp)
    return glob.glob(os.path.join(tmp, '**', '*.shp'), recursive=True)[0]

tmp = tempfile.mkdtemp()
lim = gpd.read_file(extract(os.path.join(ROOT, 'STEP_BM_SIG_DATA', 'Limite_STEPBM.lpkx'), tmp + '/a'))
comp = gpd.read_file(extract(os.path.join(ROOT, 'STEP_BM_SIG_DATA', 'STEP_BM_Compo.lpkx'), tmp + '/b'))
x0, y0, x1, y1 = lim.total_bounds
cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
to_wgs = Transformer.from_crs(lim.crs, 4326, always_xy=True)

def local(x, y):
    return [round(x - cx + HX, 2), round(cy - y + HZ, 2)]

def rings_of(geom):
    polys = geom.geoms if geom.geom_type == 'MultiPolygon' else [geom]
    return [[local(*c[:2]) for c in p.exterior.coords] for p in polys]

def mask_rings(name):
    im = cv2.imread(os.path.join(HERE, 'render-model', 'masks', name + '.png'), cv2.IMREAD_GRAYSCALE)
    s = im.shape[1] / W_M
    _, b = cv2.threshold(im, 60, 255, cv2.THRESH_BINARY)
    b = cv2.morphologyEx(b, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
    cs, _ = cv2.findContours(b, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    out = []
    for c in cs:
        if cv2.contourArea(c) < 60:
            continue
        c = cv2.approxPolyDP(c, 1.6, True)
        out.append([[round(p[0][0] / s, 2), round(p[0][1] / s, 2)] for p in c])
    return out

footprints = {}
for uid, srcs in FOOTPRINTS.items():
    rings = []
    for src in srcs:
        kind, name = src.split(':', 1)
        if kind == 'gis':
            sel = comp[comp['Name'] == name]
            assert len(sel), name
            for g in sel.geometry:
                rings += rings_of(g)
        else:
            rings += mask_rings(name)
    footprints[uid] = rings

b = lim.geometry.iloc[0]
corners_l = [(cx - HX, cy + HZ), (cx + HX, cy + HZ), (cx + HX, cy - HZ), (cx - HX, cy - HZ)]  # TL TR BR BL
data = {
    'source': 'GIS plan (ArcGIS, EPSG:26191 Merchich / Nord Maroc) and 3D model silhouettes — generated by tools/build_geometry.py',
    'extent': {'width': W_M, 'height': H_M},
    'areaHa': round(b.area / 1e4, 2),
    'center': [round(v, 6) for v in to_wgs.transform(b.centroid.x, b.centroid.y)],
    'imageCorners': [[round(v, 7) for v in to_wgs.transform(*c)] for c in corners_l],
    'boundary': {
        'local': rings_of(b)[0],
        'lnglat': [[round(v, 7) for v in to_wgs.transform(*c[:2])] for c in b.exterior.coords],
    },
    'footprints': footprints,
}
with open(OUT, 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, separators=(',', ':'))
print('written', OUT, {k: len(v) for k, v in footprints.items()}, data['center'], data['areaHa'])
